// 헬퍼 함수들
export function getLevelById(id: number): Level | undefined {
  return curriculum.find(level => level.id === id);
}

export function getLessonById(lessonId: string): { level: Level; lesson: Lesson } | undefined {
  for (const level of curriculum) {
    const lesson = level.lessons.find(l => l.id === lessonId);
    if (lesson) {
      return { level, lesson };
    }
  }
  return undefined;
}

export function getNextLesson(currentLessonId: string): { level: Level; lesson: Lesson } | undefined {
  const [levelId, lessonNum] = currentLessonId.split('-').map(Number);
  const currentLevel = curriculum.find(l => l.id === levelId);

  if (!currentLevel) return undefined;

  const currentIndex = currentLevel.lessons.findIndex(l => l.id === currentLessonId);

  // 같은 레벨의 다음 레슨
  if (currentIndex < currentLevel.lessons.length - 1) {
    return { level: currentLevel, lesson: currentLevel.lessons[currentIndex + 1] };
  }

  // 다음 레벨의 첫 레슨
  const nextLevel = curriculum.find(l => l.id === levelId + 1);
  if (nextLevel && nextLevel.lessons.length > 0) {
    return { level: nextLevel, lesson: nextLevel.lessons[0] };
  }

  return undefined;
}

export function getPrevLesson(currentLessonId: string): { level: Level; lesson: Lesson } | undefined {
  const [levelId, lessonNum] = currentLessonId.split('-').map(Number);
  const currentLevel = curriculum.find(l => l.id === levelId);

  if (!currentLevel) return undefined;

  const currentIndex = currentLevel.lessons.findIndex(l => l.id === currentLessonId);

  // 같은 레벨의 이전 레슨
  if (currentIndex > 0) {
    return { level: currentLevel, lesson: currentLevel.lessons[currentIndex - 1] };
  }

  // 이전 레벨의 마지막 레슨
  const prevLevel = curriculum.find(l => l.id === levelId - 1);
  if (prevLevel && prevLevel.lessons.length > 0) {
    return { level: prevLevel, lesson: prevLevel.lessons[prevLevel.lessons.length - 1] };
  }

  return undefined;
}
