async def generate_tts(scene_name: str, text: str) -> None:
    """Generate TTS for a single scene."""
    output_path = os.path.join(OUTPUT_DIR, f"{scene_name}.mp3")

    # 텍스트 정리 (불필요한 공백 제거)
    cleaned_text = " ".join(text.split())

    print(f"Generating: {scene_name}...")

    communicate = edge_tts.Communicate(cleaned_text, VOICE)
    await communicate.save(output_path)

    print(f"  ✓ Saved: {output_path}")

async def main():
    # 출력 디렉토리 생성
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    print(f"Generating TTS for Lesson 1-3: 퍼셉트론 구조")
    print(f"Voice: {VOICE}")
    print(f"Output directory: {OUTPUT_DIR}")
    print("-" * 50)

    # 모든 씬에 대해 TTS 생성
    for scene_name, text in SCENES.items():
        await generate_tts(scene_name, text)

    print("-" * 50)
    print("All TTS files generated successfully!")

if __name__ == "__main__":
    asyncio.run(main())
