async def generate_audio(scene_name: str, text: str):
    """단일 씬의 오디오 생성"""
    output_path = os.path.join(OUTPUT_DIR, f"{scene_name}.mp3")

    communicate = edge_tts.Communicate(text.strip(), "ko-KR-SunHiNeural")
    await communicate.save(output_path)
    print(f"Generated: {output_path}")

async def main():
    # 출력 디렉토리 생성
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    # 모든 씬의 오디오 생성
    tasks = [generate_audio(name, text) for name, text in SCENES.items()]
    await asyncio.gather(*tasks)

    print(f"\nAll audio files generated in {OUTPUT_DIR}")

if __name__ == "__main__":
    asyncio.run(main())
