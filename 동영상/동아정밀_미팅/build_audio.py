async def synth_one(idx, text):
    out = AUDIO / f"narration_{idx:02d}.mp3"
    if out.exists():
        out.unlink()
    com = edge_tts.Communicate(text, VOICE, rate=RATE, pitch=PITCH)
    await com.save(str(out))
    print(f"  - {out.name}  ({len(text)} chars)")

async def main():
    # Clean up leftover narration_11.mp3 / narration_12.mp3
    for stale in [AUDIO / "narration_11.mp3", AUDIO / "narration_12.mp3"]:
        if stale.exists():
            stale.unlink()
            print(f"  removed stale: {stale.name}")
    print(f"Voice: {VOICE}  rate={RATE}  pitch={PITCH}")
    for i, t in enumerate(NARRATIONS, start=1):
        await synth_one(i, t)
    print("Done.")

asyncio.run(main())
